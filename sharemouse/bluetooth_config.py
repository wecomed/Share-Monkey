"""User-facing setup instructions; importing this module never accesses Bluetooth."""

def setup_help(platform):
    common = (
        '蓝牙直连配置（无需 Wi-Fi、IP 地址或路由器）\n\n'
        '1. 两台电脑都安装 Share Monkey v0.5.8 或更新版本，并开启系统蓝牙。\n'
        '2. 两端在“连接与设备”选择“蓝牙直连”。键鼠接在哪台电脑，那台选择“使用本机键鼠”，另一台选择“接受另一台电脑控制”。\n'
        '3. 两端输入相同的配对密码，4 位数字即可，也支持更长密码。连接前，先在使用本机键鼠的一端进入“键鼠与屏幕”，设好对方位于左侧还是右侧。\n'
        '4. 先在 Mac 点击“开启蓝牙等待”。首次使用时允许 Share Monkey 访问蓝牙。\n'
        '5. 在 Windows 的设备列表选择发现的 Mac，然后点击“连接 Mac”。\n'
        '6. 两端显示“蓝牙已连接”后，移动到刚才设定的屏幕边缘即可切换；F12 返回本机。若需修改左右位置，请先断开连接。\n\n'
        '无需先在系统蓝牙设置中添加或配对两台电脑，也不用把 Mac 添加为“蓝牙键盘/鼠标”。本软件在应用内使用密码加密配对。\n\n'
        '蓝牙服务的连接方向固定为 Windows 连接 Mac，但键鼠可以由任意一端控制。两端都必须运行客户端。\n\n'
        '蓝牙模式支持键鼠和最多 8 KB 的文本剪贴板；发送文件与更长文本请切换到局域网。首次测试建议两机相距 1–2 米。\n\n'
        '暂时断线或休眠恢复后，两端会自动恢复等待和连接，无需重新输入密码。手动点击“断开”或退出软件会停止重连；再次启动软件后需输入密码。关闭主窗口仍可继续共享。\n\n'
        'Windows 默认开启“关屏保持共享”，允许显示器关闭，并请求共享期间继续运行。真正睡眠、合盖和系统省电策略仍可能暂停蓝牙，唤醒后自动重连。'
    )
    if platform == 'darwin':
        return common + (
            '\n\nMac 排查：\n'
            '• 系统设置 → 蓝牙：确认已开启。\n'
            '• 系统设置 → 隐私与安全性 → 蓝牙：允许 Share Monkey。拒绝后需在这里手动重新开启并重启软件。\n'
            '• 辅助功能和输入监控权限仍需保留。\n'
            '• 请从新版 Share Monkey.app 开启蓝牙。未携带蓝牙用途说明的 Python/终端直接运行会拒绝启动蓝牙，避免被系统结束。\n'
            '• 从源码开发蓝牙功能时，也必须使用 Info.plist 包含 NSBluetoothAlwaysUsageDescription 的应用容器；仅给终端授权无法代替这项声明。'
        )
    return common + (
        '\n\nWindows 排查：\n'
        '• 设置 → 蓝牙和设备：确认蓝牙已开启，飞行模式已关闭。\n'
        '• 设备管理器 → 蓝牙：确认适配器正常并已安装厂商驱动，需支持低功耗蓝牙（BLE）中央设备角色。\n'
        '• 本版使用 Windows 11 的蓝牙接口；无需安装串口驱动、手填 COM 端口或开放网络防火墙端口。\n'
        '• 看不到 Mac 时先确认 Mac 已点击“开启蓝牙等待”，并已允许蓝牙权限；不要仅依据系统蓝牙设备列表判断。'
    )
